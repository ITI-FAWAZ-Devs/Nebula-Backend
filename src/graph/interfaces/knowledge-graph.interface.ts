export interface GraphNode {
  id: string;
  labels: string[];
  properties: Record<string, unknown>;
}

export interface GraphRelationship {
  id: string;
  type: string;
  startNodeId: string;
  endNodeId: string;
  properties: Record<string, unknown>;
}

export interface KnowledgeGraph {
  repositoryId: string;
  nodes: GraphNode[];
  relationships: GraphRelationship[];
}
